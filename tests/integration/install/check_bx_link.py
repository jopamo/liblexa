#!/usr/bin/env python3
"""Audit a bx executable linked with Liblexa and its fetch compile/link inputs.

Run check_install.py on the staged Liblexa prefix separately. This
checks the consumer graph, including the feature flags that would otherwise
let a successful bx build silently omit HTML support.
For a static build, --link-map=PATH checks a map generated by adding
-Wl,-Map=PATH to that build's final link command.
"""

import json
from pathlib import Path
import re
import shlex
import subprocess
import sys


INHERITED = re.compile(r"croco", re.I)
INHERITED_SYMBOL = re.compile(r"\b(?:croco_|CR_)\w*", re.I)


def run(args, **kwargs):
    result = subprocess.run(args, capture_output=True, text=True, check=False,
                            **kwargs)
    if result.returncode:
        raise ValueError(f"{args[0]} failed: {result.stderr.strip()}")
    return result.stdout


def check(build, prefix, candidate, link_map=None):
    metadata = list(prefix.glob("lib*/pkgconfig/liblexa.pc"))
    if len(metadata) != 1:
        raise ValueError("expected one staged Liblexa pkg-config file")
    library = metadata[0].parents[1]
    core_library = library / "liblexa"
    html = library / "liblexa-html-candidate"
    commands = json.loads((build / "compile_commands.json").read_text())
    if not isinstance(commands, list) or not commands:
        raise ValueError("missing bx compile graph")
    fetch = []
    for entry in commands:
        source = (Path(entry["directory"]) / entry["file"]).resolve(strict=True)
        if INHERITED.search(str(source)):
            raise ValueError(f"bx compiles inherited source: {source}")
        if "libbx_fetch_core.a.p/" in entry["output"]:
            args = shlex.split(entry["command"])
            fetch.append((entry, args))
    if not fetch or not any(Path(entry["file"]).name == "parser.c"
                            for entry, _ in fetch):
        raise ValueError("missing bx HTML parser compilation")

    # Trace the actual fetch headers, not just -I paths: a stale installed
    # A foreign header can otherwise remain a silent source dependency.
    staged_headers = False
    for entry, args in fetch:
        for option in ("-MQ", "-MF", "-MT", "-o"):
            if option in args:
                index = args.index(option)
                del args[index:index + 2]
        args = [arg for arg in args if arg not in ("-MD", "-MMD", "-c")]
        trace = subprocess.run([*args, "-fsyntax-only", "-H"],
                               cwd=entry["directory"], capture_output=True,
                               text=True, check=False)
        if trace.returncode:
            raise ValueError(f"fetch header trace failed: {trace.stderr.strip()}")
        for line in trace.stderr.splitlines():
            match = re.match(r"^\.+ (.+)$", line)
            if not match:
                continue
            header = (Path(entry["directory"]) / match[1]).resolve()
            if INHERITED.search(str(header)):
                raise ValueError(f"bx fetch includes inherited header: {header}")
            if "/liblexa/" in str(header):
                if not header.is_relative_to(prefix / "include/liblexa"):
                    raise ValueError(f"bx fetch includes unstaged Liblexa header: {header}")
                staged_headers = True
    if not staged_headers:
        raise ValueError("bx fetch did not include staged Liblexa headers")

    link = shlex.split(run(["ninja", "-C", str(build), "-t", "commands", "bx"])
                       .splitlines()[-1])
    if INHERITED.search(" ".join(link)):
        raise ValueError("bx final link uses inherited input")
    binary = build / "bx"
    if not binary.is_file():
        raise ValueError("missing bx executable")
    dependencies = run(["readelf", "-d", str(binary)])
    needed = re.findall(r"\(NEEDED\).*?\[(.*?)\]", dependencies)
    extension = ".a" if not needed else ".so"
    required = {str(core_library) + extension}
    if candidate:
        required.add(str(html) + extension)
    if not required.issubset(link):
        raise ValueError(f"bx final link missing staged Liblexa inputs: "
                         f"{sorted(required - set(link))}")
    if link_map is not None:
        if needed or "-Wl,-Map=" + str(link_map) not in link:
            raise ValueError("link map is not from this static bx link")
        found = set()
        with link_map.open() as stream:
            for line in stream:
                if INHERITED.search(line):
                    raise ValueError("bx static link map contains inherited input")
                found.update(path for path in required if path in line)
        if found != required:
            raise ValueError(f"bx static link map missing Liblexa archives: "
                             f"{sorted(required - found)}")
    if not candidate and (str(html) + extension in link
                          or "liblexa-html-candidate.so" in needed):
        raise ValueError("unqualified HTML candidate in production bx link")
    if INHERITED.search(" ".join(needed)):
        raise ValueError("bx dynamically needs inherited library")
    if INHERITED_SYMBOL.search(
        run(["nm", "-g", "--defined-only", str(binary)])
    ):
        raise ValueError("bx executable defines inherited symbols")
    symbols = (run(["nm", "-D", "-u", str(binary)]) if needed else
               run(["nm", "-g", "--defined-only", str(binary)]))
    if needed and INHERITED_SYMBOL.search(symbols):
        raise ValueError("bx executable has unresolved inherited symbols")
    expected = (r"\bU lxa_html_document_parse(?:@|$)" if needed else
                r"\b[A-Z] lxa_html_document_parse$")
    if not re.search(expected, symbols, re.M):
        raise ValueError("bx executable does not use Liblexa HTML parser")
    if needed and (candidate and "liblexa-html-candidate.so" not in needed
                   or "liblexa.so" not in needed):
        raise ValueError("bx does not dynamically need staged Liblexa libraries")


if __name__ == "__main__":
    try:
        options = sys.argv[3:]
        map_options = [option for option in options
                       if option.startswith("--link-map=")]
        candidate = "--candidate-html" in options
        if (len(sys.argv) < 3 or len(map_options) > 1
            or len(options) != len(map_options) + int(candidate)
            or any(not option.split("=", 1)[-1] for option in map_options)):
            sys.exit("usage: check_bx_link.py BX_BUILD PREFIX "
                     "[--candidate-html] [--link-map=PATH]")
        check(Path(sys.argv[1]).resolve(strict=True),
              Path(sys.argv[2]).resolve(strict=True),
              candidate=candidate,
              link_map=(Path(map_options[0].split("=", 1)[1]).resolve(strict=True)
                        if map_options else None))
    except (OSError, KeyError, TypeError, ValueError, IndexError) as exc:
        sys.exit(f"bx Liblexa link: {exc}")
